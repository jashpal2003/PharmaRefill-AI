# TEST 1: Cartesia Sonic-2 Live TTS & Audio Generation
# -------------------------------------------------------------
def test_cartesia_live():
    print("[TEST 1/3] Testing Cartesia Sonic-2 Live TTS Endpoint...")
    if not CARTESIA_API_KEY or "your_" in CARTESIA_API_KEY:
        print("  ❌ ERROR: CARTESIA_API_KEY is not set or contains placeholder.\n")
        return False

    url = "https://api.cartesia.ai/tts/bytes"
    headers = {
        "X-API-Key": CARTESIA_API_KEY,
        "Cartesia-Version": "2024-06-10",
        "Content-Type": "application/json"
    }
    
    test_phrase = "Hello! This is a live voice generated by Cartesia Sonic-2 for Community Care Pharmacy."
    payload = {
        "model_id": "sonic-2",
        "transcript": test_phrase,
        "voice": {
            "mode": "id",
            "id": CARTESIA_VOICE_ID
        },
        "output_format": {
            "container": "wav",
            "encoding": "pcm_s16le",
            "sample_rate": 24000
        },
        "voice_settings": {
            "speed": 0.92
        }
    }

    t0 = time.time()
    try:
        resp = requests.post(url, headers=headers, json=payload, timeout=10)
        latency = int((time.time() - t0) * 1000)
        
        if resp.status_code == 200:
            audio_bytes = resp.content
            output_file = Path("cartesia_test_output.wav")
            output_file.write_bytes(audio_bytes)
            
            print(f"  ✅ SUCCESS: Cartesia returned HTTP 200 in {latency}ms!")
            print(f"  📦 Audio Format: {resp.headers.get('Content-Type')}")
            print(f"  📊 Audio Size:   {len(audio_bytes):,} bytes")
            print(f"  💾 Saved Audio:  {output_file.resolve()} (Open to listen to real Skylar voice!)")
            print(f"  🔗 You can also check your API request count on: https://play.cartesia.ai/usage\n")
            return True
        else:
            print(f"  ❌ FAILED: Cartesia returned HTTP {resp.status_code}")
            print(f"  Details: {resp.text}\n")
            return False
    except Exception as e:
        print(f"  ❌ EXCEPTION: Could not reach Cartesia: {e}\n")
        return False

