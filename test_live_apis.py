# TEST 3: AssemblyAI v3 Universal Streaming WebSocket Handshake
# -------------------------------------------------------------
async def test_assemblyai_streaming_ws():
    print("[TEST 3/3] Testing AssemblyAI v3 Universal Streaming WebSocket...")
    if not ASSEMBLYAI_API_KEY or "your_" in ASSEMBLYAI_API_KEY:
        print("  ❌ ERROR: ASSEMBLYAI_API_KEY is not set.\n")
        return False

    url = "wss://streaming.assemblyai.com/v3/ws?sample_rate=16000"
    headers = {"Authorization": ASSEMBLYAI_API_KEY}

    t0 = time.time()
    try:
        async with websockets.connect(url, additional_headers=headers) as ws:
            # 1. Wait for Begin message
            msg = await asyncio.wait_for(ws.recv(), timeout=5.0)
            latency = int((time.time() - t0) * 1000)
            data = json.loads(msg)
            print(f"  ✅ SUCCESS: Connected to AssemblyAI Universal Streaming v3 in {latency}ms!")
            print(f"  Handshake Message: {data}")
            
            # Send session termination
            await ws.send(json.dumps({"type": "Terminate"}))
            print("  Session terminated cleanly.\n")
            return True
    except Exception as e:
        print(f"  ❌ EXCEPTION: Could not connect to streaming WebSocket: {e}\n")
        return False

